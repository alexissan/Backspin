import AppKit
import BackspinCore
import Foundation
import ImageIO
import Observation
import UniformTypeIdentifiers

@MainActor @Observable
public final class ClipStore {
    public private(set) var history: ClipHistory
    public var items: [ClipItem] { history.items }

    /// While true, pasteboard changes are ignored. Persisted in defaults under "isPaused".
    public var isPaused: Bool {
        didSet {
            guard !isPreview, isPaused != oldValue else { return }
            defaults.set(isPaused, forKey: Keys.isPaused)
        }
    }

    /// Persisted under "historyLimit"; setting it applies `history.setLimit` and deletes evicted blob files.
    public var historyLimit: Int {
        didSet {
            guard historyLimit != oldValue else { return }
            if !isPreview { defaults.set(historyLimit, forKey: Keys.historyLimit) }
            removeBlobs(of: history.setLimit(historyLimit))
            scheduleSave()
        }
    }

    @ObservationIgnored private let isPreview: Bool
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private let directory: URL?
    @ObservationIgnored private let blobsDirectory: URL?
    @ObservationIgnored private let previewImages: [UUID: NSImage]
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var selfWrite: (changeCount: Int, id: UUID)?
    @ObservationIgnored private var saveTask: Task<Void, Never>?
    @ObservationIgnored private let imageCache = NSCache<NSUUID, NSImage>()
    @ObservationIgnored private let thumbnailCache = NSCache<NSString, NSImage>()

    private enum Keys {
        static let isPaused = "isPaused"
        static let historyLimit = "historyLimit"
    }

    private enum Limits {
        static let maxImageBytes = 25 * 1024 * 1024
        static let maxTextBytes = 2 * 1024 * 1024
    }

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private struct Envelope: Codable {
        var version: Int
        var items: [ClipItem]
    }

    public init(directory: URL, defaults: UserDefaults = .standard) {
        let blobs = directory.appendingPathComponent("blobs", isDirectory: true)
        try? FileManager.default.createDirectory(at: blobs, withIntermediateDirectories: true)

        let storedLimit = defaults.integer(forKey: Keys.historyLimit)
        let limit = storedLimit > 0 ? storedLimit : ClipHistory.defaultLimit

        self.isPreview = false
        self.defaults = defaults
        self.directory = directory
        self.blobsDirectory = blobs
        self.previewImages = [:]
        self.isPaused = defaults.bool(forKey: Keys.isPaused)
        self.historyLimit = limit
        self.history = ClipHistory(items: Self.loadIndex(in: directory), limit: limit)
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    public init(previewItems: [ClipItem], images: [UUID: NSImage] = [:]) {
        self.isPreview = true
        self.defaults = .standard
        self.directory = nil
        self.blobsDirectory = nil
        self.previewImages = images
        self.isPaused = false
        self.historyLimit = ClipHistory.defaultLimit
        self.history = ClipHistory(items: previewItems)
        self.lastChangeCount = 0
    }

    /// ~/Library/Application Support/Backspin
    public static var defaultDirectory: URL {
        URL.applicationSupportDirectory.appendingPathComponent("Backspin", isDirectory: true)
    }

    // MARK: Monitoring

    public func startMonitoring() {
        guard !isPreview, timer == nil else { return }
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if let selfWrite, selfWrite.changeCount == count {
            self.selfWrite = nil
            history.bump(id: selfWrite.id, at: Date())
            scheduleSave()
            return
        }
        guard !isPaused else { return }
        capture(from: pasteboard, source: NSWorkspace.shared.frontmostApplication)
    }

    // MARK: Capture

    @discardableResult
    public func capture(from pasteboard: NSPasteboard, source: NSRunningApplication?) -> ClipItem? {
        let types = pasteboard.types ?? []
        guard Self.skippedTypes.isDisjoint(with: types.map(\.rawValue)) else { return nil }

        let sourceID = source?.bundleIdentifier
        let sourceName = source?.localizedName

        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            let text = urls.map(\.path).joined(separator: "\n")
            let item = ClipItem(
                kind: .file,
                text: text,
                byteCount: urls.reduce(0) { $0 + Self.fileSize(of: $1) },
                sourceBundleID: sourceID,
                sourceName: sourceName,
                contentHash: ContentClassifier.contentHash(text: text)
            )
            return record(item)
        }

        let string = pasteboard.string(forType: .string)
        let hasText = string.map { !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty } ?? false

        if let item = imageItem(
            from: pasteboard,
            types: types,
            string: hasText ? string : nil,
            sourceBundleID: sourceID,
            sourceName: sourceName
        ) {
            return record(item)
        }

        guard let string, hasText, string.utf8.count <= Limits.maxTextBytes else { return nil }
        var item = ClipItem(
            kind: ContentClassifier.kind(of: string),
            text: string,
            byteCount: string.utf8.count,
            sourceBundleID: sourceID,
            sourceName: sourceName,
            contentHash: ContentClassifier.contentHash(text: string)
        )
        if let blobsDirectory, let rtf = pasteboard.data(forType: .rtf), !rtf.isEmpty {
            let name = "\(item.id.uuidString).rtf"
            if (try? rtf.write(to: blobsDirectory.appendingPathComponent(name))) != nil {
                item.richTextFile = name
            }
        }
        return record(item)
    }

    private func imageItem(
        from pasteboard: NSPasteboard,
        types: [NSPasteboard.PasteboardType],
        string: String?,
        sourceBundleID: String?,
        sourceName: String?
    ) -> ClipItem? {
        guard let blobsDirectory else { return nil }
        let pngData = pasteboard.data(forType: .png)
        let tiffData = pasteboard.data(forType: .tiff)
        guard let raw = pngData ?? tiffData, raw.count <= Limits.maxImageBytes else { return nil }

        let isTextCopy = types.contains(.rtf) || string.map { ContentClassifier.kind(of: $0) != .link } ?? false
        guard !isTextCopy else { return nil }

        guard let rep = NSBitmapImageRep(data: raw) else { return nil }
        let png: Data
        if let pngData, pngData == raw {
            png = pngData
        } else if let converted = rep.representation(using: .png, properties: [:]) {
            png = converted
        } else {
            return nil
        }
        guard png.count <= Limits.maxImageBytes else { return nil }

        let id = UUID()
        let name = "\(id.uuidString).png"
        guard (try? png.write(to: blobsDirectory.appendingPathComponent(name))) != nil else { return nil }
        return ClipItem(
            id: id,
            kind: .image,
            imageFile: name,
            pixelWidth: rep.pixelsWide,
            pixelHeight: rep.pixelsHigh,
            byteCount: png.count,
            sourceBundleID: sourceBundleID,
            sourceName: sourceName,
            contentHash: ContentClassifier.contentHash(data: png)
        )
    }

    private func record(_ item: ClipItem) -> ClipItem {
        let outcome = history.record(item)
        if outcome.wasRepeat {
            removeBlobs(of: [item])
        }
        removeBlobs(of: outcome.evicted)
        scheduleSave()
        return outcome.item
    }

    private static func fileSize(of url: URL) -> Int {
        (try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0
    }

    // MARK: Images

    public func image(for item: ClipItem) -> NSImage? {
        if isPreview { return previewImages[item.id] }
        if let cached = imageCache.object(forKey: item.id as NSUUID) { return cached }
        guard let url = blobURL(item.imageFile), let image = NSImage(contentsOf: url) else { return nil }
        imageCache.setObject(image, forKey: item.id as NSUUID)
        return image
    }

    public func thumbnail(for item: ClipItem, side: CGFloat) -> NSImage? {
        let key = "\(item.id.uuidString)@\(Int(side.rounded()))" as NSString
        if let cached = thumbnailCache.object(forKey: key) { return cached }

        let source: CGImageSource?
        if isPreview {
            source = previewImages[item.id]?.tiffRepresentation.flatMap { CGImageSourceCreateWithData($0 as CFData, nil) }
        } else {
            source = blobURL(item.imageFile).flatMap { CGImageSourceCreateWithURL($0 as CFURL, nil) }
        }
        guard let source else { return nil }

        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
            kCGImageSourceThumbnailMaxPixelSize: max(1, Int((side * 2).rounded())),
        ]
        guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let thumbnail = NSImage(
            cgImage: cgImage,
            size: NSSize(width: CGFloat(cgImage.width) / 2, height: CGFloat(cgImage.height) / 2)
        )
        thumbnailCache.setObject(thumbnail, forKey: key)
        return thumbnail
    }

    private func blobURL(_ name: String?) -> URL? {
        guard let name, let blobsDirectory else { return nil }
        return blobsDirectory.appendingPathComponent(name)
    }

    private func pngData(for item: ClipItem) -> Data? {
        if let url = blobURL(item.imageFile), let data = try? Data(contentsOf: url) { return data }
        guard let tiff = previewImages[item.id]?.tiffRepresentation else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    // MARK: Pasteboard output

    public func write(_ item: ClipItem, plainTextOnly: Bool = false, to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link, .color:
            guard let text = item.text else { return }
            pasteboard.setString(text, forType: .string)
            if !plainTextOnly, let url = blobURL(item.richTextFile),
               let rtf = try? Data(contentsOf: url) {
                pasteboard.setData(rtf, forType: .rtf)
            }
        case .image:
            if let png = pngData(for: item) {
                pasteboard.setData(png, forType: .png)
                if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation {
                    pasteboard.setData(tiff, forType: .tiff)
                }
            }
        case .file:
            guard let text = item.text else { return }
            let paths = text.split(separator: "\n").map(String.init)
            let urls = paths.map { URL(fileURLWithPath: $0) as NSURL }
            pasteboard.writeObjects(urls)
            pasteboard.addTypes([.string], owner: nil)
            pasteboard.setString(text, forType: .string)
        }
        if pasteboard === NSPasteboard.general {
            selfWrite = (pasteboard.changeCount, item.id)
        }
    }

    // MARK: Mutations

    public func togglePin(_ item: ClipItem) {
        guard history.togglePin(id: item.id) != nil else { return }
        scheduleSave()
    }

    public func delete(_ item: ClipItem) {
        guard let removed = history.remove(id: item.id) else { return }
        removeBlobs(of: [removed])
        scheduleSave()
    }

    public func clear(keepPinned: Bool) {
        removeBlobs(of: history.clear(keepPinned: keepPinned))
        scheduleSave()
    }

    // MARK: Persistence

    public func flush() {
        saveTask?.cancel()
        saveTask = nil
        guard let directory else { return }
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        encoder.outputFormatting = [.sortedKeys]
        guard let data = try? encoder.encode(Envelope(version: 1, items: history.items)) else { return }
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try? data.write(to: directory.appendingPathComponent("index.json"), options: .atomic)
    }

    private func scheduleSave() {
        guard !isPreview else { return }
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            try? await Task.sleep(for: .milliseconds(500))
            guard !Task.isCancelled else { return }
            self?.flush()
        }
    }

    private static func loadIndex(in directory: URL) -> [ClipItem] {
        let url = directory.appendingPathComponent("index.json")
        guard let data = try? Data(contentsOf: url) else { return [] }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        if let envelope = try? decoder.decode(Envelope.self, from: data) {
            return envelope.items
        }
        let aside = directory.appendingPathComponent("index.corrupt.json")
        try? FileManager.default.removeItem(at: aside)
        try? FileManager.default.moveItem(at: url, to: aside)
        return []
    }

    private func removeBlobs(of removed: [ClipItem]) {
        for item in removed {
            imageCache.removeObject(forKey: item.id as NSUUID)
            guard !isPreview else { continue }
            for name in [item.imageFile, item.richTextFile] {
                if let url = blobURL(name) { try? FileManager.default.removeItem(at: url) }
            }
        }
    }
}
